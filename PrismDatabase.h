#ifndef PRISM_DATABASE_H
#define PRISM_DATABASE_H

#include "BasicDatabase.h"

#include <vector>

using namespace std;

// Adds PRISM model generation and execution functionality to BasicDatabase
struct PrismDatabase : public BasicDatabase {
  // helper fields, not in the database:
  string reset_dcs; // the PRISM string that resets defensive measures, caught attacker flags, and steps, to minimize the number of states in the model
  string reset_m; // the PRISM string that resets machines, to minimize the number of states in the model
  string targets_reached;
  vector<Asset *> cut_assets; // used when cutting the IT infrastructure graph into two subgraphs
  vector<Asset *> source_assets; // if nonempty, the attacker can start with any one of these assets (if empty then it starts with no assets); different PRISM queries are executed for each of these assets
  vector<Asset *> starting_assets; // the attacker has all these assets at the start, starting_assets and source_assets cannot both be nonempty

  void compute_helper_fields();
  void generate_prism(const char *fname); // generate a PRISM model from the database tables, write to the file with the given name
  void generate_props(const char *fname, int mode = 0); // generate a PRISM props file for the models generated by generate_prism(), write to the file with the given name
  void execute_prism(vector<double> &res, int mode = 0);
};
#endif
